// starter.js — 新建待办文件时写进去的示例内容，以及"没有打开文件"时的提示语。
// 纯字符串，没有 DOM 依赖，所以 app.js 与测试共用同一份措辞。
//
// 示例的用意：新用户第一次打开时窗口里什么都没有，光说"点 ＋ 新建"不够——
// 文件建好之后还得知道怎么用。与其放一篇手册，不如放几条能直接点、直接改的示例，
// 用户改着改着就学会了，学会后整块删掉。
//
// 必须保留"父任务 + 缩进注释"这一对：有子项的待办在主列表会折叠成徽标，
// 打开详情面板是改任务名最直觉的入口；没有这条示例，没人会发现面板存在。

/* 每一行都以调用方给的换行符结尾（Windows 上新建文件用 \r\n，记事本才不乱）。 */
export function starterText(nl = '\r\n') {
  const lines = [
    '这些是示例，看懂后直接删掉这一整块。',
    '',
    '**开始使用**',
    '',
    '- [ ] 在空白处点右键，「在末尾添加分组」就能加一个分组',
    '- [ ] 点左边的小方框就能勾掉我，再点一次恢复',
    '- [ ] 右键点我，菜单里能编辑、删除；鼠标移到我右边露出小加号，点它就在下面加一条',
    '- [ ] 双击我打开右边的详情面板，任务名在面板里改',
    '- [ ] 按 Ctrl+Z 撤销；改动会自动保存，没有保存按钮',
    '- [ ] 我是父任务，双击我打开面板能看到下面挂着的东西',
    '    - 我是挂在父任务下面的注释',
  ];
  return lines.map((t) => t + nl).join('');
}

/* 缺文件时的提示。图标序号由调用方在运行时按顶栏实际顺序算出来（fileIdx 从 1 起），
   所以以后调整顶栏按钮顺序，这句话会自己跟着变，不会指错地方。
   0.4.2 起“打开 / 新建”合进同一枚下拉，所以只报一个序号，动作让用户在菜单里选；
   算不出来（0 或负数）时退化成不带数字的说法，绝不写出“第 0 个”。 */
export function missingHint(fileIdx) {
  const head = '目前没有打开待办 Markdown 文件。';
  if (fileIdx >= 1) {
    return `${head}\n请点击上方的第 ${fileIdx} 个图标，在菜单里选择「打开文件」或「新建文件」。`;
  }
  return `${head}\n请点击上方打开或新建文件的图标，在菜单里选择「打开文件」或「新建文件」。`;
}
