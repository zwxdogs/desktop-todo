// Version bookkeeping for the release script.
// The version lives in exactly one place (tauri.conf.json); every other copy is
// written from it, and a mismatch is a hard error rather than a silent drift.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
    parseVersion,
    bumpVersion,
    readTauriVersion,
    readCargoVersion,
    readCargoLockVersion,
    checkVersions,
    writeVersions,
    assertNewer,
} from './version.mjs';

const TAURI = `{
  "$schema": "https://schema.tauri.app/config/2",
  "productName": "DesktopTodo",
  "version": "0.4.1",
  "identifier": "com.zwxdogs.desktoptodo"
}
`;

const CARGO = `[package]
name = "desktop-todo"
version = "0.4.1"
edition = "2021"
license = "MIT"

[dependencies]
serde = { version = "1", features = ["derive"] }
`;

const CARGO_LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "desktop-todo"
version = "0.4.1"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.219"
`;

function fixture() {
    const dir = mkdtempSync(join(tmpdir(), 'dt-version-'));
    mkdirSync(join(dir, 'app', 'src-tauri'), { recursive: true });
    writeFileSync(join(dir, 'app', 'src-tauri', 'tauri.conf.json'), TAURI);
    writeFileSync(join(dir, 'app', 'src-tauri', 'Cargo.toml'), CARGO);
    writeFileSync(join(dir, 'app', 'src-tauri', 'Cargo.lock'), CARGO_LOCK);
    return dir;
}

function cleanup(dir) {
    rmSync(dir, { recursive: true, force: true });
}

test('parseVersion accepts x.y.z and rejects anything else', () => {
    assert.deepEqual(parseVersion('0.4.1'), { major: 0, minor: 4, patch: 1 });
    for (const bad of ['0.4', 'v0.4.1', '0.4.1-beta', ' 0.4.1', '']) {
        assert.throws(() => parseVersion(bad), /version/i, bad);
    }
});

test('bumpVersion moves exactly one part and resets the rest', () => {
    assert.equal(bumpVersion('0.4.1', 'patch'), '0.4.2');
    assert.equal(bumpVersion('0.4.1', 'minor'), '0.5.0');
    assert.equal(bumpVersion('0.4.1', 'major'), '1.0.0');
    assert.throws(() => bumpVersion('0.4.1', 'huge'), /patch|minor|major/);
});

test('reads the version from tauri.conf.json and Cargo.toml', () => {
    const dir = fixture();
    try {
        assert.equal(readTauriVersion(dir), '0.4.1');
        assert.equal(readCargoVersion(dir), '0.4.1');
        assert.equal(readCargoLockVersion(dir), '0.4.1');
    } finally {
        cleanup(dir);
    }
});

test('checkVersions names a stale Cargo.lock', () => {
    const dir = fixture();
    try {
        writeFileSync(join(dir, 'app', 'src-tauri', 'Cargo.lock'), CARGO_LOCK.replace('0.4.1', '0.4.0'));
        const result = checkVersions(dir);
        assert.equal(result.ok, false);
        assert.equal(result.mismatches.length, 1);
        assert.match(result.mismatches[0], /Cargo\.lock/);
        assert.match(result.mismatches[0], /0\.4\.0/);
    } finally {
        cleanup(dir);
    }
});

test('checkVersions is ok when every copy agrees', () => {
    const dir = fixture();
    try {
        assert.deepEqual(checkVersions(dir), { ok: true, mismatches: [] });
    } finally {
        cleanup(dir);
    }
});

test('checkVersions reports each place that disagrees', () => {
    const dir = fixture();
    try {
        writeFileSync(join(dir, 'app', 'src-tauri', 'Cargo.toml'), CARGO.replace('0.4.1', '0.4.0'));
        const result = checkVersions(dir);
        assert.equal(result.ok, false);
        assert.equal(result.mismatches.length, 1);
        assert.match(result.mismatches[0], /Cargo\.toml/);
        assert.match(result.mismatches[0], /0\.4\.0/);
    } finally {
        cleanup(dir);
    }
});

test('writeVersions syncs every copy and leaves the rest alone', () => {
    const dir = fixture();
    try {
        assert.equal(writeVersions(dir, '0.4.2'), '0.4.2');
        assert.equal(readTauriVersion(dir), '0.4.2');
        assert.equal(readCargoVersion(dir), '0.4.2');
        assert.equal(readCargoLockVersion(dir), '0.4.2');
        assert.match(readFileSync(join(dir, 'app', 'src-tauri', 'tauri.conf.json'), 'utf8'), /"productName": "DesktopTodo"/);
        assert.match(readFileSync(join(dir, 'app', 'src-tauri', 'Cargo.toml'), 'utf8'), /serde = \{ version = "1"/);
        assert.match(readFileSync(join(dir, 'app', 'src-tauri', 'Cargo.lock'), 'utf8'), /name = "serde"\nversion = "1\.0\.219"/);
        assert.deepEqual(checkVersions(dir), { ok: true, mismatches: [] });
        assert.throws(() => writeVersions(dir, 'nope'), /version/i);
        assert.equal(readTauriVersion(dir), '0.4.2');
    } finally {
        cleanup(dir);
    }
});

test('writeVersions refuses a Cargo.toml without a package version', () => {
    const dir = fixture();
    try {
        writeFileSync(join(dir, 'app', 'src-tauri', 'Cargo.toml'), '[package]\nname = "desktop-todo"\n');
        assert.throws(() => writeVersions(dir, '0.4.2'), /Cargo\.toml/);
    } finally {
        cleanup(dir);
    }
});

test('writeVersions refuses a Cargo.lock without the root package', () => {
    const dir = fixture();
    try {
        writeFileSync(join(dir, 'app', 'src-tauri', 'Cargo.lock'), CARGO_LOCK.replace('name = "desktop-todo"', 'name = "other"'));
        assert.throws(() => writeVersions(dir, '0.4.2'), /Cargo\.lock/);
        assert.equal(readTauriVersion(dir), '0.4.1');
    } finally {
        cleanup(dir);
    }
});

test('assertNewer rejects equal, lower and malformed versions', () => {
    assert.equal(assertNewer('0.4.1', '0.4.2'), '0.4.2');
    assert.equal(assertNewer('0.4.1', '0.5.0'), '0.5.0');
    assert.throws(() => assertNewer('0.4.1', '0.4.1'), /already the current/);
    assert.throws(() => assertNewer('0.4.1', '0.3.9'), /lower than/);
    assert.throws(() => assertNewer('0.4.1', '1.0'), /invalid version/);
});